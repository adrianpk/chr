package gate

import (
	"crypto/sha256"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const (
	// WoodpeckerFeedbackMechanism defines a package boundary constant.
	WoodpeckerFeedbackMechanism = "woodpecker-status"

	woodpeckerConfigFile = ".woodpecker.yml"
	woodpeckerMarker     = "# Generated by chr gate woodpecker init."
	// Retain ownership of existing generated configs independently of display branding.
	woodpeckerPreviousMarkerDigest = "ccb62051ed6aef48a4ba7d43c159763516a7a9f9dab16336e036bfaa6fd13841"
)

// WoodpeckerInitRequest describes a package boundary value.
type WoodpeckerInitRequest struct {
	ProjectDir string
	DryRun     bool
	Write      bool
}

// WoodpeckerInitResult describes a package boundary value.
type WoodpeckerInitResult struct {
	ConfigPath        string
	Action            WoodpeckerAction
	Snippet           string
	FeedbackMechanism string
	Wrote             bool
}

// InitWoodpecker executes the corresponding package operation.
func InitWoodpecker(request WoodpeckerInitRequest) (WoodpeckerInitResult, error) {
	normalized, err := normalizeWoodpeckerInitRequest(request)
	if err != nil {
		return WoodpeckerInitResult{}, err
	}

	snippet := WoodpeckerSnippet()
	result := WoodpeckerInitResult{
		ConfigPath:        normalized.ConfigPath,
		Action:            WoodpeckerActionDryRun,
		Snippet:           snippet,
		FeedbackMechanism: WoodpeckerFeedbackMechanism,
	}

	if normalized.DryRun {
		return result, nil
	}

	content, err := os.ReadFile(normalized.ConfigPath)
	if errors.Is(err, os.ErrNotExist) {
		err = os.WriteFile(normalized.ConfigPath, []byte(snippet), 0o644)
		if err != nil {
			return WoodpeckerInitResult{}, fmt.Errorf("write Woodpecker gate config: %w", err)
		}

		result.Action = WoodpeckerActionCreated
		result.Wrote = true

		return result, nil
	}

	if err != nil {
		return WoodpeckerInitResult{}, fmt.Errorf("read Woodpecker gate config: %w", err)
	}

	if !normalized.Write {
		result.Action = WoodpeckerActionExists

		return result, nil
	}

	if !hasWoodpeckerMarker(string(content)) {
		return WoodpeckerInitResult{}, fmt.Errorf("woodpecker config already exists without chr marker: %s", normalized.ConfigPath)
	}

	err = os.WriteFile(normalized.ConfigPath, []byte(snippet), 0o644)
	if err != nil {
		return WoodpeckerInitResult{}, fmt.Errorf("update Woodpecker gate config: %w", err)
	}

	result.Action = WoodpeckerActionUpdated
	result.Wrote = true

	return result, nil
}

func hasWoodpeckerMarker(content string) bool {
	if strings.Contains(strings.ToLower(content), strings.ToLower(woodpeckerMarker)) {
		return true
	}

	for _, line := range strings.Split(content, "\n") {
		digest := sha256.Sum256([]byte(strings.TrimSpace(line)))
		if fmt.Sprintf("%x", digest) == woodpeckerPreviousMarkerDigest {
			return true
		}
	}

	return false
}

// WoodpeckerSnippet executes the corresponding package operation.
func WoodpeckerSnippet() string {
	return woodpeckerMarker + `
when:
  - event: pull_request
    branch: main

steps:
  - name: chr-dev-main-gate
    image: golang:1.25
    commands:
      - git fetch origin main
      - go install forge.adrianpk.com/chr/cmd/chr@latest
      - chr gate dev-main --dir . --base ${CHR_GATE_BASE:-origin/main} --head ${CHR_GATE_HEAD:-HEAD}
`
}

type woodpeckerInitRequest struct {
	ConfigPath string
	DryRun     bool
	Write      bool
}

func normalizeWoodpeckerInitRequest(request WoodpeckerInitRequest) (woodpeckerInitRequest, error) {
	projectDir := request.ProjectDir
	if projectDir == "" {
		projectDir = "."
	}

	absoluteProjectDir, err := filepath.Abs(projectDir)
	if err != nil {
		return woodpeckerInitRequest{}, fmt.Errorf("resolve project directory: %w", err)
	}

	info, err := os.Stat(absoluteProjectDir)
	if err != nil {
		return woodpeckerInitRequest{}, fmt.Errorf("stat project directory: %w", err)
	}

	if !info.IsDir() {
		return woodpeckerInitRequest{}, fmt.Errorf("project directory is not a directory: %s", absoluteProjectDir)
	}

	return woodpeckerInitRequest{
		ConfigPath: filepath.Join(absoluteProjectDir, woodpeckerConfigFile),
		DryRun:     request.DryRun,
		Write:      request.Write,
	}, nil
}

// WoodpeckerAction identifies the existing configuration-write outcome.
type WoodpeckerAction string

const (
	// WoodpeckerActionDryRun reports a preview without a write.
	WoodpeckerActionDryRun WoodpeckerAction = "dry-run"
	// WoodpeckerActionCreated reports a newly written configuration.
	WoodpeckerActionCreated WoodpeckerAction = "created"
	// WoodpeckerActionExists reports a retained configuration without overwrite.
	WoodpeckerActionExists WoodpeckerAction = "exists"
	// WoodpeckerActionUpdated reports an owned configuration replacement.
	WoodpeckerActionUpdated WoodpeckerAction = "updated"
)
