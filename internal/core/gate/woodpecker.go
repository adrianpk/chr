package gate

import (
	"crypto/sha256"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const (
	// GateWoodpeckerFeedbackMechanism defines a package boundary constant.
	GateWoodpeckerFeedbackMechanism = "woodpecker-status"

	gateWoodpeckerConfigFile = ".woodpecker.yml"
	gateWoodpeckerMarker     = "# Generated by chr gate woodpecker init."
	// Retain ownership of existing generated configs independently of display branding.
	gateWoodpeckerPreviousMarkerDigest = "ccb62051ed6aef48a4ba7d43c159763516a7a9f9dab16336e036bfaa6fd13841"
)

// GateWoodpeckerInitRequest describes a package boundary value.
type GateWoodpeckerInitRequest struct {
	ProjectDir string
	DryRun     bool
	Write      bool
}

// GateWoodpeckerInitResult describes a package boundary value.
type GateWoodpeckerInitResult struct {
	ConfigPath        string
	Action            string
	Snippet           string
	FeedbackMechanism string
	Wrote             bool
}

// InitGateWoodpecker executes the corresponding package operation.
func InitGateWoodpecker(request GateWoodpeckerInitRequest) (GateWoodpeckerInitResult, error) {
	normalized, err := normalizeGateWoodpeckerInitRequest(request)
	if err != nil {
		return GateWoodpeckerInitResult{}, err
	}

	snippet := GateWoodpeckerSnippet()
	result := GateWoodpeckerInitResult{
		ConfigPath:        normalized.ConfigPath,
		Action:            "dry-run",
		Snippet:           snippet,
		FeedbackMechanism: GateWoodpeckerFeedbackMechanism,
	}

	if normalized.DryRun {
		return result, nil
	}

	content, err := os.ReadFile(normalized.ConfigPath)
	if errors.Is(err, os.ErrNotExist) {
		err = os.WriteFile(normalized.ConfigPath, []byte(snippet), 0o644)
		if err != nil {
			return GateWoodpeckerInitResult{}, fmt.Errorf("write Woodpecker gate config: %w", err)
		}

		result.Action = "created"
		result.Wrote = true

		return result, nil
	}

	if err != nil {
		return GateWoodpeckerInitResult{}, fmt.Errorf("read Woodpecker gate config: %w", err)
	}

	if !normalized.Write {
		result.Action = "exists"

		return result, nil
	}

	if !hasGateWoodpeckerMarker(string(content)) {
		return GateWoodpeckerInitResult{}, fmt.Errorf("woodpecker config already exists without chr marker: %s", normalized.ConfigPath)
	}

	err = os.WriteFile(normalized.ConfigPath, []byte(snippet), 0o644)
	if err != nil {
		return GateWoodpeckerInitResult{}, fmt.Errorf("update Woodpecker gate config: %w", err)
	}

	result.Action = "updated"
	result.Wrote = true

	return result, nil
}

func hasGateWoodpeckerMarker(content string) bool {
	if strings.Contains(strings.ToLower(content), strings.ToLower(gateWoodpeckerMarker)) {
		return true
	}

	for _, line := range strings.Split(content, "\n") {
		digest := sha256.Sum256([]byte(strings.TrimSpace(line)))
		if fmt.Sprintf("%x", digest) == gateWoodpeckerPreviousMarkerDigest {
			return true
		}
	}

	return false
}

// GateWoodpeckerSnippet executes the corresponding package operation.
func GateWoodpeckerSnippet() string {
	return gateWoodpeckerMarker + `
when:
  - event: pull_request
    branch: main

steps:
  - name: chr-dev-main-gate
    image: golang:1.25
    commands:
      - git fetch origin main
      - go install forge.adrianpk.com/chr/cmd/chr@latest
      - chr gate dev-main --dir . --base ${CHR_GATE_BASE:-origin/main} --head ${CHR_GATE_HEAD:-HEAD}
`
}

type gateWoodpeckerInitRequest struct {
	ConfigPath string
	DryRun     bool
	Write      bool
}

func normalizeGateWoodpeckerInitRequest(request GateWoodpeckerInitRequest) (gateWoodpeckerInitRequest, error) {
	projectDir := request.ProjectDir
	if projectDir == "" {
		projectDir = "."
	}

	absoluteProjectDir, err := filepath.Abs(projectDir)
	if err != nil {
		return gateWoodpeckerInitRequest{}, fmt.Errorf("resolve project directory: %w", err)
	}

	info, err := os.Stat(absoluteProjectDir)
	if err != nil {
		return gateWoodpeckerInitRequest{}, fmt.Errorf("stat project directory: %w", err)
	}

	if !info.IsDir() {
		return gateWoodpeckerInitRequest{}, fmt.Errorf("project directory is not a directory: %s", absoluteProjectDir)
	}

	return gateWoodpeckerInitRequest{
		ConfigPath: filepath.Join(absoluteProjectDir, gateWoodpeckerConfigFile),
		DryRun:     request.DryRun,
		Write:      request.Write,
	}, nil
}
