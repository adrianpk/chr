package chc

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const (
	GateWoodpeckerFeedbackMechanism = "woodpecker-status"

	gateWoodpeckerConfigFile = ".woodpecker.yml"
	gateWoodpeckerMarker     = "# Generated by ChrysoCoord gate woodpecker init."
)

type GateWoodpeckerInitRequest struct {
	ProjectDir string
	DryRun     bool
	Write      bool
}

type GateWoodpeckerInitResult struct {
	ConfigPath        string
	Action            string
	Snippet           string
	FeedbackMechanism string
	Wrote             bool
}

func InitGateWoodpecker(request GateWoodpeckerInitRequest) (GateWoodpeckerInitResult, error) {
	normalized, err := normalizeGateWoodpeckerInitRequest(request)
	if err != nil {
		return GateWoodpeckerInitResult{}, err
	}

	snippet := GateWoodpeckerSnippet()
	result := GateWoodpeckerInitResult{
		ConfigPath:        normalized.ConfigPath,
		Action:            "dry-run",
		Snippet:           snippet,
		FeedbackMechanism: GateWoodpeckerFeedbackMechanism,
	}

	if normalized.DryRun {
		return result, nil
	}

	content, err := os.ReadFile(normalized.ConfigPath)
	if errors.Is(err, os.ErrNotExist) {
		err = os.WriteFile(normalized.ConfigPath, []byte(snippet), 0o644)
		if err != nil {
			return GateWoodpeckerInitResult{}, fmt.Errorf("write Woodpecker gate config: %w", err)
		}

		result.Action = "created"
		result.Wrote = true

		return result, nil
	}

	if err != nil {
		return GateWoodpeckerInitResult{}, fmt.Errorf("read Woodpecker gate config: %w", err)
	}

	if !normalized.Write {
		result.Action = "exists"

		return result, nil
	}

	if !strings.Contains(string(content), gateWoodpeckerMarker) {
		return GateWoodpeckerInitResult{}, fmt.Errorf("woodpecker config already exists without ChrysoCoord marker: %s", normalized.ConfigPath)
	}

	err = os.WriteFile(normalized.ConfigPath, []byte(snippet), 0o644)
	if err != nil {
		return GateWoodpeckerInitResult{}, fmt.Errorf("update Woodpecker gate config: %w", err)
	}

	result.Action = "updated"
	result.Wrote = true

	return result, nil
}

func GateWoodpeckerSnippet() string {
	return gateWoodpeckerMarker + `
when:
  - event: pull_request
    branch: main

steps:
  - name: chc-dev-main-gate
    image: golang:1.25
    commands:
      - git fetch origin main
      - go install forge.adrianpk.com/chc/cmd/chc@latest
      - chc gate dev-main --dir . --base ${CHC_GATE_BASE:-origin/main} --head ${CHC_GATE_HEAD:-HEAD}
`
}

type gateWoodpeckerInitRequest struct {
	ConfigPath string
	DryRun     bool
	Write      bool
}

func normalizeGateWoodpeckerInitRequest(request GateWoodpeckerInitRequest) (gateWoodpeckerInitRequest, error) {
	projectDir := request.ProjectDir
	if projectDir == "" {
		projectDir = "."
	}

	absoluteProjectDir, err := filepath.Abs(projectDir)
	if err != nil {
		return gateWoodpeckerInitRequest{}, fmt.Errorf("resolve project directory: %w", err)
	}

	info, err := os.Stat(absoluteProjectDir)
	if err != nil {
		return gateWoodpeckerInitRequest{}, fmt.Errorf("stat project directory: %w", err)
	}

	if !info.IsDir() {
		return gateWoodpeckerInitRequest{}, fmt.Errorf("project directory is not a directory: %s", absoluteProjectDir)
	}

	return gateWoodpeckerInitRequest{
		ConfigPath: filepath.Join(absoluteProjectDir, gateWoodpeckerConfigFile),
		DryRun:     request.DryRun,
		Write:      request.Write,
	}, nil
}
